#!/bin/bash
# ================================================================
# gen_grub_cfg.sh — Generate GRUB config for DialectForge OS
# ================================================================
# Reads dfos.conf for build-time options (password protection, etc.)
# Usage: sudo ./gen_grub_cfg.sh [--install]
#   --install: also mount disk image and write grub.cfg to it
#   without flag: prints to stdout for review
# ================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "${SCRIPT_DIR}/dfos.conf"

KERNEL="/boot/vmlinuz-${DFOS_KERNEL_VERSION}"
INITRD="/boot/initramfs-dfos.img"
ROOTUUID="4d0bc99e-d477-4c33-a360-4cfdf02cd236"

# Helper: wrap a menuentry with the right access flag
# $1 = "safe" (unrestricted) or "dangerous" (password-locked)
entry_flags() {
    if [ "$DFOS_GRUB_PASSWORD_ENABLED" = "true" ]; then
        if [ "$1" = "dangerous" ]; then
            echo "--users ${DFOS_GRUB_SUPERUSER} "
        else
            echo "--unrestricted "
        fi
    fi
}

submenu_flags() {
    if [ "$DFOS_GRUB_PASSWORD_ENABLED" = "true" ]; then
        echo " --unrestricted"
    fi
}

# ---- Generate ----
cat << GRUBEOF
serial --unit=0 --speed=115200
terminal_input serial console
terminal_output serial console
# DialectForge OS 1.0 — Universal Boot Configuration
# AUTO-GENERATED by gen_grub_cfg.sh — do not edit by hand
# Build config: dfos.conf | Password protection: ${DFOS_GRUB_PASSWORD_ENABLED}

set timeout=10
set default=0
set gfxmode=auto
set gfxpayload=keep

insmod all_video
insmod font
insmod gfxterm

loadfont /boot/grub/fonts/unicode.pf2
loadfont /boot/grub/fonts/dejavu-full.pf2

if [ "\$grub_platform" = "efi" ]; then
    insmod efi_gop
    insmod efi_uga
fi

set menu_color_normal=white/black
set menu_color_highlight=black/light-gray
set rootuuid=${ROOTUUID}
GRUBEOF

# Password block (only if enabled)
if [ "$DFOS_GRUB_PASSWORD_ENABLED" = "true" ]; then
    cat << PWEOF

# GRUB password protection — prevents editing boot params
set superusers="${DFOS_GRUB_SUPERUSER}"
password_pbkdf2 ${DFOS_GRUB_SUPERUSER} ${DFOS_GRUB_PASSWORD_HASH}
PWEOF
fi

cat << GRUBEOF

# ==========================================
#  LIVE BOOT OPTIONS
# ==========================================

menuentry "DialectForge OS 1.0 — Live" --class dialectforge --class linux $(entry_flags safe){
    search --no-floppy --fs-uuid --set=root \$rootuuid
    linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nouveau.modeset=0 df.mem_defer=1 amdgpu.modeset=0 loglevel=7
    initrd ${INITRD}
}

menuentry "DialectForge OS 1.0 — Live (verbose boot)" --class dialectforge --class linux $(entry_flags safe){
    search --no-floppy --fs-uuid --set=root \$rootuuid
    linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nouveau.modeset=0 amdgpu.modeset=0 df.mem_defer=1 loglevel=7
    initrd ${INITRD}
}

menuentry "DialectForge OS 1.0 — Live (persistent)" --class dialectforge --class linux $(entry_flags safe){
    search --no-floppy --fs-uuid --set=root \$rootuuid
    linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nouveau.modeset=0 amdgpu.modeset=0 df.mem_defer=1 df.persist=1 quiet loglevel=3
    initrd ${INITRD}
}

menuentry "DialectForge OS 1.0 — Live (safe graphics)" --class dialectforge --class linux $(entry_flags safe){
    search --no-floppy --fs-uuid --set=root \$rootuuid
    linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset nofb vga=normal df.mem_defer=1 loglevel=7
    initrd ${INITRD}
}

# ==========================================
#  SAFE MODE
# ==========================================

menuentry "DialectForge OS 1.0 — Safe Mode (no memory protection, restricted)" --class dialectforge --class linux $(entry_flags dangerous){
    search --no-floppy --fs-uuid --set=root \$rootuuid
    linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset df.safemode=1 ip=off nonetwork single loglevel=7
    initrd ${INITRD}
}

# ==========================================
#  INSTALL
# ==========================================

menuentry "Install DialectForge OS to disk" --class calamares --class linux $(entry_flags safe){
    search --no-floppy --fs-uuid --set=root \$rootuuid
    linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nouveau.modeset=0 amdgpu.modeset=0 df.mem_defer=1 df.install=1 quiet loglevel=3
    initrd ${INITRD}
}

# ==========================================
#  ADVANCED OPTIONS
# ==========================================

submenu "Advanced Options"$(submenu_flags) {
    menuentry "DialectForge OS — No memory protection" --class dialectforge $(entry_flags dangerous){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset df.mem_off=1 quiet
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — Single-user (rescue)" --class dialectforge $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset df.mem_defer=1 single loglevel=7
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — Emergency shell (no init)" --class dialectforge $(entry_flags dangerous){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset init=/bin/bash loglevel=7
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — Serial console (115200)" --class dialectforge $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200n8 console=ttyS0,115200 console=tty0 nomodeset df.mem_defer=1 loglevel=7
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — ACPI off (old hardware)" --class dialectforge $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset acpi=off noapic df.mem_defer=1 loglevel=7
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — RAM-only (toram)" --class dialectforge $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset df.mem_defer=1 toram quiet
        initrd ${INITRD}
    }

    menuentry "Hardware Detection Report" --class hwinfo $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset df.mem_defer=1 df.hwdetect=1 loglevel=7
        initrd ${INITRD}
    }
}

# ==========================================
#  FALLBACK / RECOVERY
# ==========================================

submenu "Fallback / Recovery"$(submenu_flags) {
    menuentry "DialectForge OS — Minimal drivers" --class dialectforge $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=5 console=ttyS0,115200 console=tty0 nomodeset nofb vga=normal acpi=off noapic irqpoll df.mem_defer=1 loglevel=7
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — Force text console" --class dialectforge $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=5 console=ttyS0,115200 console=tty0 nomodeset nofb nosplash vga=normal df.mem_defer=1 loglevel=7
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — Slow USB (10s delay)" --class dialectforge $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=10 console=ttyS0,115200 console=tty0 nomodeset df.mem_defer=1 loglevel=7
        initrd ${INITRD}
    }

    menuentry "DialectForge OS — Debug shell before init" --class dialectforge $(entry_flags dangerous){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset df.mem_defer=1 rd.break loglevel=7
        initrd ${INITRD}
    }

    menuentry "Boot from first hard drive (legacy)" --class hd $(entry_flags safe){
        set root=(hd1)
        chainloader +1
    }

    menuentry "Boot from second hard drive" --class hd $(entry_flags safe){
        set root=(hd2)
        chainloader +1
    }
}

# ==========================================
#  HARDWARE DIAGNOSTICS
# ==========================================

submenu "Hardware Diagnostics"$(submenu_flags) {
    menuentry "Memory Test (Memtest86+) — BIOS" --class memtest $(entry_flags safe){
        linux16 /boot/memtest86+x64.bin
    }

    menuentry "Memory Test (Memtest86+) — UEFI" --class memtest $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        chainloader /boot/memtest86+x64.efi
    }

    menuentry "Hardware Info — Quick Scan" --class hwinfo $(entry_flags safe){
        search --no-floppy --fs-uuid --set=root \$rootuuid
        linux ${KERNEL} root=UUID=\$rootuuid rootwait rootdelay=3 console=ttyS0,115200 console=tty0 nomodeset df.mem_defer=1 df.hwdetect=1 loglevel=7
        initrd ${INITRD}
    }
}

# ==========================================
#  OTHER
# ==========================================

menuentry "Boot from local disk" --class hd $(entry_flags safe){
    set root=(hd1)
    chainloader +1
}

menuentry "UEFI Firmware Settings" --class firmware $(entry_flags safe){
    fwsetup
}
GRUBEOF
